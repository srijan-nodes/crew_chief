        internal static bool tableCheck()
        {
            foreach (var id in Enum.GetValues(typeof(ID)))
            {
                if (!speechCommands.ContainsKey((ID)id) &&
                    (ID)id != ID.NO_COMMAND)
                {
                    if (!controllerCommands.ContainsKey((ID)id))
                    {
                        Console.WriteLine("Missing " + id);
                        return false;
                    }
                }
            }
            return true;
        }
        /// <summary>
        /// Given a list of SpeechCommand identifiers return each with its corresponding
        /// speech strings
        /// </summary>
        /// <param name="commandList">SpeechCommand identifiers</param>
        /// <returns>SpeechCommand identifier,its corresponding speech strings</returns>
        public static IEnumerable<(ID, string[])> GenerateTuples(List<ID> commandList)
        {
            foreach (var command in commandList)
            {
                if (speechCommands.TryGetValue(command, out string[] speechCommand))
                {
                    yield return (command, speechCommand);
                }
            }
        }

        /// <summary>
        /// Convert recognised speech into a SpeechCommand enum
        /// </summary>
        /// <param name="commands">Possible commands</param>
        /// <param name="recognisedSpeech">The recognised speech</param>
        /// <returns>SpeechCommand ID, NO_COMMAND if no match</returns>
        public static ID SpeechToCommand(List<ID> commands, string recognisedSpeech, Boolean logMatch = false)
        {
            ID cmd = ID.NO_COMMAND;
            foreach (var command in GenerateTuples(commands))
            {
                if (SpeechRecogniser.ResultContains(recognisedSpeech, command.Item2, logMatch))
                {
                    cmd = command.Item1;
                    break;
                }
            }
            return cmd;
        }

        /// <summary>
        /// Convert recognised speech into a SpeechCommand enum
        /// </summary>
        /// <param name="commands">Possible commands</param>
        /// <param name="recognisedSpeech">The recognised speech</param>
        /// <returns>SpeechCommand ID, NO_COMMAND if no match</returns>
        public static ID SpeechEndsWithToCommand(List<ID> commands, string recognisedSpeech, Boolean logMatch = false)
        {
            ID cmd = ID.NO_COMMAND;
            foreach (var command in GenerateTuples(commands))
            {
                if (recognisedSpeech.EndsWith(command.Item2[0]))
                {
                    cmd = command.Item1;
                    break;
                }
            }
            return cmd;
        }

