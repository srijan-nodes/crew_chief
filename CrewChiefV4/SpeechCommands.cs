        /// <summary>
        /// Convert controller button label into a SpeechCommand enum
        /// </summary>
        /// <param name="commands">Possible commands</param>
        /// <param name="controllerLabel">The recognised speech</param>
        /// <returns>SpeechCommand ID, NO_COMMAND if no match</returns>
        public static ID ControllerToCommand(List<ID> commands, string controllerLabel)
        {
            ID cmd = ID.NO_COMMAND;
            if (ControllerConfiguration.builtInActionMappings.ContainsValue(controllerLabel))
            {
                foreach (var command in GenerateTuples2(commands))
                {
                    if (command.Item2.Contains(controllerLabel))
                    {
                        cmd = command.Item1;
                        break;
                    }
                }
            }
            return cmd;
        }
